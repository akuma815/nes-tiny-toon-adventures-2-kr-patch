"""Explicit project-contained cleanup plan; evidence stays losslessly restorable."""
from collections import Counter
from pathlib import Path
import json
import re
from seal_nonplay171 import R

folder = R / 'work/cleanup214'
inventory = json.loads((folder / 'inventory.json').read_text('utf-8'))['files']
groups = {}
for item in inventory:
    parts = item['path'].split('/')
    if len(parts) >= 4 and parts[:2] == ['qa', 'dialogue']:
        groups.setdefault('/'.join(parts[:3]), []).append(item)
    elif len(parts) >= 3 and parts[0] in ('build', 'dist', 'work'):
        groups.setdefault('/'.join(parts[:2]), []).append(item)
    elif len(parts) >= 4 and parts[:2] in (['qa', 'release'], ['qa', 'apply'], ['qa', 'patch']):
        groups.setdefault('/'.join(parts[:3]), []).append(item)
preserved = {
    'build/dialogue_kr_poc_051', 'build/opening11_poc_053', 'build/opening11_poc_055',
    'build/homebooth11_candidate_057', 'build/ordinary11_candidate_059',
    'build/text11_candidate_062', 'build/text11_211_rebuild062',
    'dist/TinyToonAdventures2_KR_Text11_Candidate062_20261009',
    'dist/TinyToonAdventures2_KR_Opening11_PoC055_Layout6_20261009',
    'dist/TinyToonAdventures2_KR_Ordinary11_Candidate059_Apply206_20261009',
    'work/cleanup214',
}
selected = []
for group, items in groups.items():
    if group in preserved or 'user' in group.lower():
        continue
    if any(Path(z['path']).suffix.lower() in ('.sav', '.srm', '.mss', '.state') for z in items):
        continue
    if group.startswith('qa/dialogue/'):
        name = group.rsplit('/', 1)[1]
        if any(token in name for token in ('050', '051', '055', '177', '178', '179', '180', '181', '182')):
            continue
        if name.startswith('cards033_') and not name.endswith('_irq'):
            continue
        if sum(Path(z['path']).name.startswith('frame_') for z in items) < 30:
            continue
    selected.append(group)
selected.sort()
for group in selected:
    p = (R / group).resolve(strict=True)
    assert p.is_relative_to(R.resolve()) and p != R.resolve()
    assert not any(p.is_relative_to((R / n).resolve()) for n in ('original', 'workspace', 'scripts', 'tools', 'docs', 'manifests', 'backups', 'config', 'extracted'))

# Preserve every existing local document/HTML target as a live file after archival.
linked = set()
text_files = [R / 'README.md', R / 'AGENTS.md', *sorted((R / 'docs').rglob('*.md')),
              *sorted((R / 'workspace/review').rglob('*.html')), *sorted((R / 'dist').rglob('*.html'))]
for p in text_files:
    s = p.read_text('utf-8-sig')
    refs = [a or b for a, b in re.findall(r'\]\((?:<([^>\n]+)>|([^()\n]+))\)', s)]
    refs += re.findall(r'(?:src|href)=["\']([^"\']+)', s)
    for ref in refs:
        ref = ref.strip().split('#')[0].split('?')[0]
        if not ref or re.match('[a-z]+://', ref):
            continue
        target = (p.parent / ref).resolve()
        if target.is_relative_to(R) and target.is_file():
            linked.add(target.relative_to(R).as_posix())

archive = []
retain = []
for group in selected:
    for z in groups[group]:
        archive.append(z)
        name = Path(z['path']).name
        # Keep capture setup/provenance and every clickable target. Bulk frame payloads move to storage.
        keep_control = group.startswith('qa/dialogue/') and not name.startswith('frame_')
        keep_apply_report = group.startswith(('qa/release/', 'qa/apply/', 'qa/patch/')) and name.endswith('.json') and '/apply_verification.json' in z['path']
        if z['path'] in linked or keep_control or keep_apply_report:
            retain.append(z['path'])
            # A retained old HTML needs its neighboring static assets to remain readable.
            if name.endswith('.html'):
                prefix = str(Path(z['path']).parent).replace('\\', '/') + '/'
                retain.extend(f['path'] for f in groups[group] if f['path'].startswith(prefix) and Path(f['path']).suffix.lower() in ('.png', '.jpg', '.css', '.js'))

caches = sorted({z['path'].split('/__pycache__/')[0] + '/__pycache__' if '/__pycache__/' in z['path'] else '__pycache__'
                 for z in inventory if '/__pycache__/' in z['path'] or z['path'].startswith('__pycache__/')})
plan = {'work': 214, 'root': str(R.resolve()), 'status': 'PLANNED_NOT_DELETED',
    'archive_path': 'qa/archive/cleanup214_history.sqlite',
    'directory_targets': selected, 'files_to_archive': archive,
    'retain_live_files': sorted(set(retain)), 'cache_directory_targets': caches,
    'protected_live_roots': sorted(preserved),
    'policy': 'Store all selected history bytes bySHA in a private compressed SQLite archive; verify every object before deletion. Keep sources,SSOT,tools,records,packagesZIP,current062 and chain live. Restore document-linked files and capture setup. Only regenerated bytecode is discarded.',
    'selected_bytes': sum(z['bytes'] for z in archive), 'selected_file_count': len(archive)}
out = folder / 'plan.json'
assert not out.exists()
out.write_text(json.dumps(plan, ensure_ascii=False, indent=2) + '\n', 'utf-8')
print(json.dumps({'directories': len(selected), 'archived_file_candidates': len(archive),
    'bytes': plan['selected_bytes'], 'live_restored_files': len(set(retain)),
    'cache_directories': len(caches), 'retained_major': sorted(preserved),
    'browser_dictionary_examples': [z['path'] for z in inventory if z['path'].endswith('.bdic')][:3]}, ensure_ascii=False, indent=2))
